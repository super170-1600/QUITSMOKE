import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { resolve } from 'node:path'
import { mkdir } from 'node:fs/promises'

const runtime = resolve(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules')
const require = createRequire(resolve(runtime, 'sharp/package.json'))
const sharp = require('sharp')
const output = resolve('public/images')
await mkdir(output, { recursive: true })
for (const [source, name] of [
  ['exec-17a94179-a0df-4c1b-8c69-045787c8ce91.png', 'breath-portal-v3.webp'],
  ['exec-bd43b02a-b3e6-4534-904b-6c7afb1ff480.png', 'breath-portal-clean-v3.webp'],
]) {
  const input = resolve(homedir(), '.codex/generated_images/01a12f32-1561-74d3-ae31-6c6a6fbdf086', source)
  // Encoding only: preserve dimensions, framing, and the artwork generated by imagegen.
  const result = await sharp(input).webp({ quality: 94, effort: 6 }).toFile(resolve(output, name))
  console.log(`${name}: ${result.width} × ${result.height}, ${Math.round(result.size / 1024)} KB`)
}
